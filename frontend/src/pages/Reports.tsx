import { useMemo, useState } from 'react';
import { Download } from 'lucide-react';
import { Bar, BarChart, CartesianGrid, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts';
import { PageHeader } from '../components/common/PageHeader';
import { DataTable, type Column } from '../components/common/DataTable';
import { DateFilter, FilterBar } from '../components/common/FilterBar';
import { AsyncBoundary } from '../components/common/States';
import { useFetch } from '../hooks/useFetch';
import { reportsApi } from '../api/reports.api';
import { downloadFile, humanize, toCSV, todayISO } from '../utils/format';
import type { ReportKey, Row } from '../types';

const REPORTS: { key: ReportKey; label: string; description: string; chart: boolean; dated: boolean }[] = [
  { key: 'workload', label: 'Teacher workload', description: 'Weekly teaching load per teacher.', chart: true, dated: false },
  { key: 'department-timetable', label: 'Department timetable', description: 'Scheduled classes grouped by department.', chart: false, dated: false },
  { key: 'leaves', label: 'Teacher leave', description: 'Leave applications within the selected period.', chart: false, dated: true },
  { key: 'substitutions', label: 'Substitutions', description: 'Substitutions within the selected period.', chart: false, dated: true },
  { key: 'frequent-substitutes', label: 'Most frequent substitutes', description: 'Teachers who covered the most classes.', chart: true, dated: true },
  { key: 'course-allocation', label: 'Course allocation', description: 'Teachers and classes allocated per course.', chart: true, dated: false },
];

const isId = (k: string) => k === 'id' || k.endsWith('_id');

function formatCell(v: unknown): string {
  if (v === null || v === undefined || v === '') return '—';
  if (typeof v === 'object') return JSON.stringify(v);
  return String(v);
}

export default function Reports() {
  const [key, setKey] = useState<ReportKey>('workload');
  const [from, setFrom] = useState('');
  const [to, setTo] = useState('');
  const meta = REPORTS.find((r) => r.key === key)!;

  const { data, loading, error, reload } = useFetch(
    (s) => reportsApi.run(key, meta.dated ? { from_date: from, to_date: to } : {}, s),
    [key, from, to],
  );

  const rows: Row[] = data ?? [];
  const keys = useMemo(() => {
    const all = rows.length ? Object.keys(rows[0]) : [];
    const visible = all.filter((k) => !isId(k));
    return visible.length ? visible : all;
  }, [rows]);

  const columns: Column<Row>[] = keys.map((k) => ({
    key: k,
    header: humanize(k),
    sortValue: (r) => {
      const v = r[k];
      return typeof v === 'number' ? v : String(v ?? '');
    },
    render: (r) => formatCell(r[k]),
  }));

  const chart = useMemo(() => {
    if (!meta.chart || rows.length === 0) return null;
    const labelKey = keys.find((k) => typeof rows[0][k] === 'string');
    const valueKey = keys.find((k) => typeof rows[0][k] === 'number' || (rows[0][k] !== '' && !Number.isNaN(Number(rows[0][k])) && typeof rows[0][k] !== 'boolean' && k !== labelKey));
    if (!labelKey || !valueKey) return null;
    const data = rows.slice(0, 15).map((r) => ({ label: String(r[labelKey]), value: Number(r[valueKey]) }));
    return { data, valueKey };
  }, [meta.chart, rows, keys]);

  const exportCsv = () => downloadFile(`${key}-report-${todayISO()}.csv`, toCSV(rows, keys));

  return (
    <div>
      <PageHeader
        title="Reports"
        description="Figures are generated by the server from the live database."
        actions={
          <button className="btn-secondary" onClick={exportCsv} disabled={rows.length === 0}>
            <Download size={14} /> Export CSV
          </button>
        }
      />

      <div className="grid gap-4 lg:grid-cols-[220px_1fr]">
        <nav className="panel h-fit p-1.5" aria-label="Report type">
          {REPORTS.map((r) => (
            <button
              key={r.key}
              onClick={() => setKey(r.key)}
              aria-current={key === r.key}
              className={`block w-full rounded px-2.5 py-2 text-left text-[13px] ${key === r.key ? 'bg-primary-soft font-medium text-primary' : 'text-ink-muted hover:bg-app hover:text-ink'}`}
            >
              {r.label}
            </button>
          ))}
        </nav>

        <div className="space-y-4">
          <div className="panel">
            <div className="border-b border-line px-4 py-3">
              <h2 className="panel-title">{meta.label}</h2>
              <p className="text-xs text-ink-muted">{meta.description}</p>
            </div>
            {meta.dated && (
              <FilterBar>
                <DateFilter label="From" value={from} onChange={setFrom} />
                <DateFilter label="To" value={to} onChange={setTo} />
                {(from || to) && (
                  <button className="btn-ghost" onClick={() => { setFrom(''); setTo(''); }}>
                    Clear dates
                  </button>
                )}
              </FilterBar>
            )}
            <AsyncBoundary loading={loading} error={error} onRetry={reload}>
              {chart && (
                <div className="h-60 border-b border-line px-2 py-3" role="img" aria-label={`${meta.label} chart`}>
                  <ResponsiveContainer width="100%" height="100%">
                    <BarChart data={chart.data} margin={{ top: 4, right: 12, left: -12, bottom: 0 }}>
                      <CartesianGrid vertical={false} stroke="#E5E7EB" />
                      <XAxis dataKey="label" tick={{ fontSize: 11, fill: '#6B7280' }} axisLine={false} tickLine={false} interval={0} />
                      <YAxis allowDecimals={false} tick={{ fontSize: 11, fill: '#6B7280' }} axisLine={false} tickLine={false} />
                      <Tooltip cursor={{ fill: '#F6F7F9' }} formatter={(v) => [String(v), humanize(chart.valueKey)]} contentStyle={{ fontSize: 12, borderRadius: 4, border: '1px solid #E5E7EB' }} />
                      <Bar dataKey="value" fill="#426A9B" radius={[2, 2, 0, 0]} maxBarSize={32} />
                    </BarChart>
                  </ResponsiveContainer>
                </div>
              )}
              <DataTable columns={columns} rows={rows} rowKey={(r) => JSON.stringify(r)} pageSize={12} emptyTitle="No data for this report" emptyHint={meta.dated ? 'Try a wider date range.' : undefined} />
            </AsyncBoundary>
          </div>
        </div>
      </div>
    </div>
  );
}
